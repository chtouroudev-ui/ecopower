def load_env():
    env = ROOT / 'data' / 'postgres.env'
    if env.is_file():
        for raw in env.read_text(encoding='utf-8-sig').splitlines():
            line = raw.strip()
            if not line or line.startswith('#') or '=' not in line:
                continue
            k, v = line.split('=', 1)
            os.environ.setdefault(k.strip(), v.strip())
    return env


def pg_type(declared: str) -> str:
    t = (declared or '').upper()
    if 'INT' in t:
        return 'BIGINT'
    if any(x in t for x in ('REAL', 'FLOA', 'DOUB')):
        return 'DOUBLE PRECISION'
    if 'BLOB' in t:
        return 'BYTEA'
    if any(x in t for x in ('NUM', 'DEC')):
        return 'NUMERIC'
    return 'TEXT'


def qident(name: str) -> str:
    return '"' + str(name).replace('"', '""') + '"'


def table_sql(src: sqlite3.Connection, schema: str, table: str):
    info = src.execute(f'PRAGMA table_info({qident(table)})').fetchall()
    src_sql_row = src.execute("SELECT sql FROM sqlite_master WHERE type='table' AND name=?", (table,)).fetchone()
    src_sql = src_sql_row[0] if src_sql_row and src_sql_row[0] else ''
    pk_cols = [r[1] for r in sorted((r for r in info if r[5]), key=lambda x: x[5])]
    single_integer_pk = len(pk_cols) == 1 and next((r for r in info if r[1] == pk_cols[0] and 'INT' in (r[2] or '').upper()), None) is not None
    cols = []
    for cid, name, dtype, notnull, default, pkpos in info:
        typ = pg_type(dtype)
        if single_integer_pk and name == pk_cols[0]:
            col = f'{qident(name)} BIGINT GENERATED BY DEFAULT AS IDENTITY'
        else:
            col = f'{qident(name)} {typ}'
        if notnull:
            col += ' NOT NULL'
        if default is not None:
            d = str(default).strip()
            if re.fullmatch(r'CURRENT_TIMESTAMP', d, re.I):
                col += ' DEFAULT CURRENT_TIMESTAMP'
            elif re.fullmatch(r'[-+]?\d+(?:\.\d+)?', d):
                col += ' DEFAULT ' + d
            elif d.upper() in {'NULL', 'TRUE', 'FALSE'}:
                col += ' DEFAULT ' + d.upper()
            elif (d.startswith("'") and d.endswith("'")) or (d.startswith('"') and d.endswith('"')):
                col += ' DEFAULT ' + d.replace('"', "'")
        cols.append(col)
    if pk_cols:
        cols.append('PRIMARY KEY (' + ','.join(qident(c) for c in pk_cols) + ')')
    sql = f'CREATE TABLE {qident(schema)}.{qident(table)} (\n  ' + ',\n  '.join(cols) + '\n)'
    return sql, info, pk_cols, single_integer_pk, src_sql



def prepare_sqlite_sources():
    """Bring legacy SQLite files to the latest shipped schema before copying."""
    old_url=os.environ.pop('NELYIO_DATABASE_URL',None)
    old_engine=os.environ.pop('NELYIO_DATABASE_ENGINE',None)
    old_skip=os.environ.get('NELYIO_SKIP_STARTUP_DETAILS_SYNC')
    old_force=os.environ.get('NELYIO_FORCE_SQLITE')
    os.environ['NELYIO_SKIP_STARTUP_DETAILS_SYNC']='1'
    os.environ['NELYIO_FORCE_SQLITE']='1'
    try:
        import app, details_store, collection_store
        import quality_metrics, quality_agents, import_workflow, group_har_import
        from supervision_db import connect as supervision_connect
        app.ensure_schema()
        app.supervision.init()
        details_store.init()
        collection_store.init(force=True)
        # Materialize lazy schemas before the PostgreSQL copy.  This avoids
        # relying on SQLite DDL translation during the first production request
        # (notably Qualite and import-job tables).
        with supervision_connect() as con:
            quality_metrics.ensure_schema(con)
            quality_agents.ensure_schema(con)
            import_workflow.ensure_schema(con)
        with app.db_connect() as con:
            group_har_import.ensure_schema(con)
    finally:
        if old_url is not None: os.environ['NELYIO_DATABASE_URL']=old_url
        if old_engine is not None: os.environ['NELYIO_DATABASE_ENGINE']=old_engine
        if old_skip is None: os.environ.pop('NELYIO_SKIP_STARTUP_DETAILS_SYNC',None)
        else: os.environ['NELYIO_SKIP_STARTUP_DETAILS_SYNC']=old_skip
        if old_force is None: os.environ.pop('NELYIO_FORCE_SQLITE',None)
        else: os.environ['NELYIO_FORCE_SQLITE']=old_force


