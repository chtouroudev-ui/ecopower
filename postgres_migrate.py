def migrate_schema(pg, schema: str, db_path: Path, reset: bool):
    if not db_path.is_file():
        print(f'[WARN] {db_path.name} absent; schema {schema} cree vide.')
        with pg.cursor() as cur:
            cur.execute(f'CREATE SCHEMA IF NOT EXISTS {qident(schema)}')
        pg.commit()
        return {'tables':0,'rows':0}
    src = sqlite3.connect(str(db_path))
    src.row_factory = sqlite3.Row
    tables = [r[0] for r in src.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name")]
    with pg.cursor() as cur:
        if reset:
            cur.execute(f'DROP SCHEMA IF EXISTS {qident(schema)} CASCADE')
        cur.execute(f'CREATE SCHEMA IF NOT EXISTS {qident(schema)}')
    pg.commit()
    total_rows=0
    identity=[]
    for table in tables:
        ddl, info, pk_cols, is_identity, src_sql = table_sql(src,schema,table)
        with pg.cursor() as cur:
            cur.execute(f'DROP TABLE IF EXISTS {qident(schema)}.{qident(table)} CASCADE')
            cur.execute(ddl)
        pg.commit()
        cols=[r[1] for r in info]
        count=src.execute(f'SELECT COUNT(*) FROM {qident(table)}').fetchone()[0]
        if count:
            select_sql='SELECT '+','.join(qident(c) for c in cols)+' FROM '+qident(table)
            copy_sql='COPY '+qident(schema)+'.'+qident(table)+' ('+','.join(qident(c) for c in cols)+') FROM STDIN'
            with pg.cursor() as cur, cur.copy(copy_sql) as cp:
                for row in src.execute(select_sql):
                    cp.write_row(tuple(row[c] for c in cols))
            pg.commit()
        total_rows += count
        if is_identity and pk_cols:
            identity.append((table,pk_cols[0]))
        print(f'[OK] {schema}.{table}: {count} lignes')
    # recreate unique indexes before non-unique indexes
    for table in tables:
        for idx in src.execute(f'PRAGMA index_list({qident(table)})').fetchall():
            # seq,name,unique,origin,partial
            name=idx[1]; unique=bool(idx[2]); origin=idx[3] if len(idx)>3 else ''
            if origin=='pk': continue
            cols=[r[2] for r in src.execute(f'PRAGMA index_info({qident(name)})').fetchall() if r[2] is not None]
            if not cols: continue
            idxname=(schema+'_'+name)[:60]
            stmt='CREATE '+('UNIQUE ' if unique else '')+'INDEX IF NOT EXISTS '+qident(idxname)+' ON '+qident(schema)+'.'+qident(table)+' ('+','.join(qident(c) for c in cols)+')'
            try:
                with pg.cursor() as cur: cur.execute(stmt)
                pg.commit()
            except Exception as exc:
                pg.rollback(); print(f'[WARN] index {schema}.{name}: {exc}')
    # Recreate SQLite foreign keys after all tables are loaded.
    for table in tables:
        groups={}
        for fk in src.execute(f'PRAGMA foreign_key_list({qident(table)})').fetchall():
            # id,seq,table,from,to,on_update,on_delete,match
            groups.setdefault(fk[0],[]).append(fk)
        for fid, rows in groups.items():
            rows=sorted(rows,key=lambda r:r[1])
            ref=rows[0][2]; from_cols=[r[3] for r in rows]; to_cols=[r[4] for r in rows]
            on_update=(rows[0][5] or 'NO ACTION').upper(); on_delete=(rows[0][6] or 'NO ACTION').upper()
            cname=f'fk_{schema}_{table}_{fid}'[:60]
            stmt=(f'ALTER TABLE {qident(schema)}.{qident(table)} ADD CONSTRAINT {qident(cname)} '
                  f'FOREIGN KEY ({",".join(qident(c) for c in from_cols)}) REFERENCES {qident(schema)}.{qident(ref)} ({",".join(qident(c) for c in to_cols)}) '
                  f'ON UPDATE {on_update} ON DELETE {on_delete}')
            try:
                with pg.cursor() as cur: cur.execute(stmt)
                pg.commit()
            except Exception as exc:
                pg.rollback(); print(f'[WARN] FK {schema}.{table}: {exc}')

    # reset identity sequences after copied IDs
    for table, pk in identity:
        try:
            with pg.cursor() as cur:
                cur.execute("SELECT pg_get_serial_sequence(%s,%s)",(f'{schema}.{table}',pk)); seq=cur.fetchone()[0]
                if seq:
                    cur.execute(f'SELECT COALESCE(MAX({qident(pk)}),0) FROM {qident(schema)}.{qident(table)}'); mx=cur.fetchone()[0]
                    cur.execute('SELECT setval(%s,%s,%s)',(seq,max(1,int(mx)),bool(mx)))
            pg.commit()
        except Exception as exc:
            pg.rollback(); print(f'[WARN] sequence {schema}.{table}: {exc}')
    src.close()
    return {'tables':len(tables),'rows':total_rows}


def verify(pg, expected):
    mismatches=[]
    for schema, db_path in DBS.items():
        if not db_path.is_file(): continue
        src=sqlite3.connect(str(db_path))
        for (table,) in src.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"):
            a=src.execute(f'SELECT COUNT(*) FROM {qident(table)}').fetchone()[0]
            with pg.cursor() as cur:
                cur.execute(f'SELECT COUNT(*) FROM {qident(schema)}.{qident(table)}'); b=cur.fetchone()[0]
            if a!=b: mismatches.append((schema,table,a,b))
        src.close()
    return mismatches


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--reset',action='store_true',help='Recreer les 4 schemas PostgreSQL depuis les SQLite actuels')
    ap.add_argument('--verify-only',action='store_true')
    args=ap.parse_args()
    env=load_env()
    dsn=os.environ.get('NELYIO_DATABASE_URL','').strip()
    if not dsn:
        raise SystemExit('NELYIO_DATABASE_URL absent. Lancez CONFIGURER_POSTGRESQL_AUTO.bat.')
    try:
        import psycopg
    except ImportError:
        raise SystemExit('psycopg absent. Lancez: py -3 -m pip install "psycopg[binary]>=3.2,<4"')
    if not args.verify_only:
        prepare_sqlite_sources()
    pg=psycopg.connect(dsn)
    if not args.verify_only:
        summary={}
        for schema,path in DBS.items(): summary[schema]=migrate_schema(pg,schema,path,args.reset)
        create_helpers(pg)
        with pg.cursor() as cur:
            cur.execute('CREATE TABLE IF NOT EXISTS public.nelyio_migration_meta(key text PRIMARY KEY,value text NOT NULL,updated_at timestamptz NOT NULL DEFAULT now())')
            cur.execute("INSERT INTO public.nelyio_migration_meta(key,value) VALUES('engine','postgresql') ON CONFLICT(key) DO UPDATE SET value=excluded.value,updated_at=now()")
